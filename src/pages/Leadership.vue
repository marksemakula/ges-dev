function injectMeta(name: string, content: string, attr = 'name') {
  const existing = document.querySelector(`meta[${attr}="${name}"]`) as HTMLMetaElement | null;
  if (existing) {
    const prev = existing.getAttribute('content') || '';
    existing.setAttribute('content', content);
    existing.dataset.prev = prev;
    injectedMeta.push(existing);
  } else {
    const el = document.createElement('meta');
    el.setAttribute(attr, name);
